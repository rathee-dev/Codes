#include <iostream>
using namespace std;
int main()
{
    int a,b;
    cout<<"Enter the value of a: "<<endl;
    cin>>a;
    cout<<"Enter the value of b: "<<endl;
    cin>>b;
    cout<<"a+b: "<<a+b<<endl;
    cout<<"a-b: "<<a-b<<endl;
    cout<<"a*b: "<<a*b<<endl;
    cout<<"a/b: "<<a/b<<endl;// As operation is between two integer value.
    cout<<"a/b: "<<(float)a/b<<endl;
    return 0;
}